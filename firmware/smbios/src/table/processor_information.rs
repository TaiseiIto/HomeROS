/// # References
/// * [SMBIOS Specification](https://www.dmtf.org/sites/default/files/standards/documents/DSP0134_3.10.0.pdf) 7.5.1 Processor Information - Processor Type
#[derive(Debug)]
enum Type {
    Other,
    Unknown,
    Central,
    Math,
    Dsp,
    Video,
}

impl From<u8> for Type {
    fn from(typ: u8) -> Self {
        match typ {
            0x01 => Self::Other,
            0x02 => Self::Unknown,
            0x03 => Self::Central,
            0x04 => Self::Math,
            0x05 => Self::Dsp,
            0x06 => Self::Video,
            _ => panic!(),
        }
    }
}

